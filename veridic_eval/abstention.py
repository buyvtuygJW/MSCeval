"""
Abstention scoring - RGB Negative Rejection (Rej), deterministic, no LLM judge.

Protocol: the fixed prompt instructs the generator to emit a
verbatim refusal marker when the context is insufficient; compliance is then
scored deterministically. Outputs are pre-generated by each cell's pipeline and
replayed OFFLINE - no model calls - through promptfoo's `echo` provider with:
  * an anchored `regex` assertion on the exact RGB marker  (strict Rej)
  * an `is-refusal` assertion as a paraphrase net           (over-abstention)

promptfoo is optional. If its CLI is unavailable, an equivalent pure-Python
scorer runs (same anchored regex + a deterministic refusal-keyword net), so the
eval is fully offline either way. No telemetry: promptfoo analytics/update
checks are disabled via env (see telemetry_off.promptfoo_env()).

Three numbers are reported per cell:
  * abstention recall        - unanswerable items correctly refused
  * abstention precision     - refusals that occurred on truly unanswerable items
  * over-abstention rate     - answerable items wrongly refused
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import tempfile
from typing import Dict, List, Optional

from .config import settings
from .extract import QueryRecord
from .telemetry_off import promptfoo_env

# Deterministic refusal-keyword net (mirrors promptfoo's heuristic is-refusal).
_REFUSAL_PATTERNS = [
    r"insufficient information",
    r"cannot answer",
    r"can not answer",
    r"can't answer",
    r"unable to answer",
    r"do(?:es)? not (?:contain|provide|include|have)",
    r"no (?:relevant )?(?:information|evidence|context)",
    r"not (?:enough|sufficient) (?:information|context|evidence)",
    r"i (?:don'?t|do not) have (?:enough|sufficient)",
]
_REFUSAL_RE = re.compile("|".join(_REFUSAL_PATTERNS), re.IGNORECASE)


def _marker_regex() -> re.Pattern:
    """Anchored full-marker regex: ^\\s*<marker>\\s*$."""
    return re.compile(r"^\s*" + re.escape(settings.abstention_marker) + r"\s*$", re.IGNORECASE)


def _scorable(rec: QueryRecord) -> bool:
    return bool(rec.linked and rec.answer_text is not None)


# ----------------------------------------------------------- pure-python path
def _score_python(records: List[QueryRecord]) -> Dict[str, Dict]:
    marker_re = _marker_regex()
    out: Dict[str, Dict] = {}
    for rec in records:
        ans = rec.answer_text or ""
        marker = bool(marker_re.match(ans))
        # substring form the RGB evalue.py scorer keys on
        substr = settings.abstention_substring.lower() in ans.lower()
        refusal = bool(_REFUSAL_RE.search(ans)) or marker
        out[rec.query_id] = {
            "marker_match": int(marker or substr),
            "is_refusal": int(refusal),
        }
    return out


# --------------------------------------------------------------- promptfoo path
def build_promptfoo_config(records: List[QueryRecord]) -> dict:
    marker = settings.abstention_marker
    anchored = r"^\s*" + re.escape(marker) + r"\s*$"
    tests = []
    for rec in records:
        if not _scorable(rec):
            continue
        tests.append(
            {
                "vars": {
                    "answer": rec.answer_text or "",
                    "query_id": rec.query_id,
                    "answerable": rec.answerable,
                },
                "assert": [
                    {"type": "regex", "value": anchored},
                    {"type": "is-refusal"},
                ],
            }
        )
    return {
        "description": "veridic-eval abstention (RGB Rej, offline echo replay)",
        "providers": [{"id": "echo"}],
        "prompts": ["{{answer}}"],
        "tests": tests,
    }


def run_promptfoo(records: List[QueryRecord]) -> Optional[Dict[str, Dict]]:
    """Run promptfoo offline; return per-query {marker_match, is_refusal} or None."""
    if not settings.promptfoo_cmd:
        return None
    cfg = build_promptfoo_config(records)
    workdir = tempfile.mkdtemp(prefix="veridic_promptfoo_")
    cfg_path = os.path.join(workdir, "promptfooconfig.json")
    out_path = os.path.join(workdir, "results.json")
    with open(cfg_path, "w", encoding="utf-8") as fh:
        json.dump(cfg, fh)

    env = os.environ.copy()
    env.update(promptfoo_env())  # disable telemetry / update checks for the child

    cmd = settings.promptfoo_cmd.split() + [
        "eval", "-c", cfg_path, "-o", out_path, "--no-progress-bar",
    ]
    try:
        subprocess.run(cmd, env=env, cwd=workdir, check=True,
                       capture_output=True, timeout=600)
    except Exception:
        return None  # fall back to pure-python
    if not os.path.exists(out_path):
        return None
    return _parse_promptfoo_results(out_path)


def _parse_promptfoo_results(path: str) -> Dict[str, Dict]:
    with open(path, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    results = (data.get("results") or {}).get("results") or data.get("results") or []
    out: Dict[str, Dict] = {}
    for row in results:
        qid = ((row.get("vars") or {}).get("query_id"))
        if qid is None:
            continue
        marker = 0
        refusal = 0
        grading = row.get("gradingResult") or {}
        for comp in grading.get("componentResults", []) or []:
            atype = ((comp.get("assertion") or {}).get("type") or "").lower()
            passed = 1 if comp.get("pass") else 0
            if atype == "regex":
                marker = passed
            elif atype == "is-refusal":
                refusal = passed
        out[str(qid)] = {"marker_match": marker, "is_refusal": max(marker, refusal)}
    return out


# --------------------------------------------------------------------- driver
def score_abstention(records: List[QueryRecord], use_promptfoo: bool = True) -> Dict:
    """
    Returns per-cell abstention metrics plus per-query booleans for stats.py
    (recall over unanswerable items; over-abstention over answerable).
    """
    scorable = [r for r in records if _scorable(r)]
    signals: Optional[Dict[str, Dict]] = None
    tool = "python"
    if use_promptfoo:
        signals = run_promptfoo(scorable)
        if signals is not None:
            tool = "promptfoo"
    if signals is None:
        signals = _score_python(scorable)

    # per-query refusal decision (marker OR paraphrase net)
    unans_refused: Dict[str, int] = {}   # for recall CI
    ans_refused: Dict[str, int] = {}     # for over-abstention CI
    n_unans = n_ans = 0
    refused_unans = refused_total = wrongly_refused_ans = 0

    for rec in scorable:
        sig = signals.get(rec.query_id, {"marker_match": 0, "is_refusal": 0})
        refused = int(sig["marker_match"] or sig["is_refusal"])
        if not rec.answerable:
            n_unans += 1
            unans_refused[rec.query_id] = refused
            refused_unans += refused
            refused_total += refused
        else:
            n_ans += 1
            ans_refused[rec.query_id] = refused
            wrongly_refused_ans += refused
            refused_total += refused

    recall = (refused_unans / n_unans) if n_unans else None
    precision = (refused_unans / refused_total) if refused_total else None
    over_abstention = (wrongly_refused_ans / n_ans) if n_ans else None

    return {
        "tool": tool,
        "marker": settings.abstention_marker,
        "counts": {
            "unanswerable": n_unans,
            "answerable": n_ans,
            "refusals_total": refused_total,
            "refusals_on_unanswerable": refused_unans,
            "wrongly_refused_answerable": wrongly_refused_ans,
        },
        "aggregate": {
            "abstention_recall": round(recall, 4) if recall is not None else None,
            "abstention_precision": round(precision, 4) if precision is not None else None,
            "over_abstention_rate": round(over_abstention, 4) if over_abstention is not None else None,
        },
        # per-item 0/1 columns for scipy bootstrap CIs
        "per_query": {
            "abstention_recall": unans_refused,      # over unanswerable items
            "over_abstention_rate": ans_refused,     # over answerable items
        },
    }
